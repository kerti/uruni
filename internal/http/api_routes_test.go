// apiDoc is the generated route table. Regenerate it with
//
//	go test ./internal/http -run TestAPIRouteTable -update
const apiDoc = "../../docs/API.md"

// TestAPIRouteTable walks the real router and compares the route table with
// docs/API.md, so a route cannot be added, moved out of the session gate or
// removed without the table (and its reviewer) noticing.
func TestAPIRouteTable(t *testing.T) {
	r, _ := testRouterAndDB(t)
	routes, ok := r.(chi.Routes)
	if !ok {
		t.Fatalf("New returned %T, want a chi router", r)
	}
	checkGolden(t, filepath.Clean(apiDoc), renderRouteTable(t, routes))
}

type routeRow struct{ method, path, auth string }

func renderRouteTable(t *testing.T, routes chi.Routes) []byte {
	t.Helper()
	var rows []routeRow
	err := chi.Walk(routes, func(method, route string, h http.Handler, mws ...func(http.Handler) http.Handler) error {
		route = strings.ReplaceAll(route, "/*/", "/")
		rows = append(rows, routeRow{method: method, path: route, auth: authOf(h, mws)})
		return nil
	})
	if err != nil {
		t.Fatalf("chi.Walk: %v", err)
	}
	sort.Slice(rows, func(i, j int) bool {
		if rows[i].path != rows[j].path {
			return rows[i].path < rows[j].path
		}
		return rows[i].method < rows[j].method
	})

	var b strings.Builder
	b.WriteString("# API routes\n\n")
	b.WriteString("Generated by `TestAPIRouteTable` (internal/http/api_routes_test.go); do not edit by hand.\n")
	b.WriteString("Regenerate with `go test ./internal/http -run TestAPIRouteTable -update`.\n\n")
	b.WriteString("Session: `required` routes sit behind the treasurer's session; `public` routes answer without one.\n")
	b.WriteString("Anything not listed falls through to the SPA (outside `/api` and `/report`) or a JSON 404 (inside `/api`).\n\n")
	b.WriteString("| Method | Path | Session |\n|---|---|---|\n")
	for _, row := range rows {
		fmt.Fprintf(&b, "| %s | `%s` | %s |\n", row.method, row.path, row.auth)
	}
	return []byte(b.String())
}

// authOf reports whether sessionRequired wraps the route: either in the
// mounted router's middleware stack or in the inline chain a Group or With
// builds around the endpoint. Routes outside /api carry no session manager at
// all and read "public".
func authOf(h http.Handler, mws []func(http.Handler) http.Handler) string {
	all := append([]func(http.Handler) http.Handler(nil), mws...)
	if ch, ok := h.(*chi.ChainHandler); ok {
		all = append(all, ch.Middlewares...)
	}
	for _, mw := range all {
		if strings.Contains(runtime.FuncForPC(reflect.ValueOf(mw).Pointer()).Name(), "sessionRequired") {
			return "required"
		}
	}
	return "public"
}
